import {test,expect} from '@playwright/test';
test('research workflow and responsive layout',async({page})=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('/');
 await expect(page.getByText('252 daily observations')).toBeVisible();
 await page.screenshot({path:'docs/overview.png',fullPage:true});
 await page.getByRole('button',{name:'Strategy Lab',exact:true}).click();
 await page.getByLabel('Strategy',{exact:true}).selectOption('hold');
 await page.getByRole('button',{name:'Run backtest',exact:true}).click();
 await expect(page.getByText('1 executed trades')).toBeVisible();
 await page.getByRole('button',{name:/Inspect BUY/}).click();
 await expect(page.getByRole('dialog')).toContainText('Initial allocation');
 await page.getByRole('button',{name:'Close ×'}).click();
 await page.getByRole('button',{name:'Scenario Replay',exact:true}).click();
 await page.getByRole('button',{name:'Reset replay'}).click();
 await expect(page.getByText('1 / 252')).toBeVisible();
 await page.getByRole('slider',{name:'Replay timeline'}).fill('80');
 await expect(page.getByText('81 / 252')).toBeVisible();
 await page.getByRole('button',{name:'Play replay'}).click();
 await page.waitForTimeout(350);
 await page.getByRole('button',{name:'Pause replay'}).click();
 await page.getByRole('button',{name:'Reality Check',exact:true}).click();
 await expect(page.getByText('Parameter sensitivity', {exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Methodology',exact:true}).click();
 await expect(page.getByText('Know what you\'re measuring.')).toBeVisible();
 await page.setViewportSize({width:390,height:844});
 await page.getByRole('button',{name:'Overview',exact:true}).click();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.screenshot({path:'docs/mobile.png',fullPage:true});
 expect(errors).toEqual([]);
});
